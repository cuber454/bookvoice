    /** Младшие байты WAV: 16-битное число с прямым порядком (little endian). */
    private fun leShort(b: ByteArray, i: Int): Int =
        (b[i].toInt() and 0xFF) or ((b[i + 1].toInt() and 0xFF) shl 8)

    /** 32-битное число WAV (little endian). */
    private fun leInt(b: ByteArray, i: Int): Int =
        leShort(b, i) or (leShort(b, i + 2) shl 16)

    /** Коды причин, по которым обрезка файл не тронула. Пишем в журнал по
     *  одному разу на код за сессию: если галочка «ничего не меняет», по этой
     *  строке видно, ЧТО именно ей помешало (msg4409 — Сергей: «на мой слух
     *  эта галочка ничего не меняет», а причина молчала).
     *  1 — это не WAV; 2 — формат не PCM; 3 — не тот звук (каналы/биты/частота);
     *  4 — нет блока data; 5 — файл подозрительного размера; 7 — сплошная
     *  тишина; 8 — после обрезки осталась бы десятая часть; 9 — тишины по краям
     *  нет вовсе (значит пауза не в тишине, а в интонации синтезатора). */
    private val trimBailLogged = HashSet<String>()

    /** Чей файл обрезаем — для строк журнала (26.09.2026). Без этого в логе не
     *  видно, отказала обрезка у основного движка или у репликового, а жалоба
     *  была именно про паузы у реплик. */
    private var trimWho: String = ""

    /** Кто сделал файл: роль и движок — одной короткой пометкой для журнала. */
    private fun whoLabel(role: Pending.Role): String =
        if (role == Pending.Role.REPLY) "реплика, ${replyEnginePackage ?: "системный"}"
        else "книга, ${enginePackage ?: "системный"}"

    /** Целевая средняя громкость фразы: −18 dBFS (26.09.2026). К ней приводим
     *  каждую фразу любого движка — тогда смена движка не слышна по громкости
     *  (гугловский читает тише, multiTTS громче). */
    private val loudTargetRms = 4125.0

    private fun trimBail(code: Int, what: String, f: File) {
        // «Дальше не повторяю» — но по каждой паре «причина + кто сделал файл»
        // отдельно: иначе отказ у репликового движка скрылся бы за таким же
        // отказом у основного (26.09.2026).
        if (!trimBailLogged.add("$code|$trimWho")) return
        Diag.log(
            appContext, "sound",
            "паузы: ${f.name} [$trimWho] не тронул — $what (причина $code; дальше не повторяю)"
        )
    }

    /** Обрезать тишину по краям синтезированного файла (msg4402). Разбираем
     *  только обычный 16-битный PCM-WAV (в том числе в «расширенном» заголовке) —
     *  если внутри что-то другое или файл не разобрался, оставляем как есть:
     *  пауза останется прежней, но чтение не сломается, а причина уйдёт в
     *  журнал через [trimBail]. Голову подрезаем сильнее хвоста — в начале
     *  тишина почти всегда «пустая», в конце в неё уходит затухание последнего
     *  слова. */
    /** Сколько времени уходит на обработку звука (26.09.2026). Серж спросил,
     *  сильно ли мы грузим процессор: отвечаем цифрами с его телефона, а не
     *  рассуждением. Считаем время прохода по отсчётам — обрезки тишины и
     *  выравнивания громкости — и пишем в журнал среднее и худшее на каждые
     *  двадцать пять фраз. */
    private var audioProcCount = 0
    private var audioProcTotalNs = 0L
    private var audioProcMaxNs = 0L

    private fun trimSilence(f: File, role: Pending.Role) {
        val t0 = System.nanoTime()
        trimSilenceInner(f, role)
        val spent = System.nanoTime() - t0
        audioProcCount++
        audioProcTotalNs += spent
        if (spent > audioProcMaxNs) audioProcMaxNs = spent
        if (audioProcCount % 25 == 0) {
            Diag.log(
                appContext, "sound",
                "обработка звука: фраз $audioProcCount, в среднем " +
                    "${fmtMs(audioProcTotalNs / audioProcCount)} мс, худшая ${fmtMs(audioProcMaxNs)} мс"
            )
        }
    }

    /** Миллисекунды с одним знаком для журнала. */
    private fun fmtMs(ns: Long): String =
        String.format(java.util.Locale.US, "%.1f", ns / 1_000_000.0)

    private fun trimSilenceInner(f: File, role: Pending.Role) {
        val b = runCatching { f.readBytes() }.getOrNull() ?: return
        val n = b.size
        if (n < 128 || n > 8_000_000) { trimBail(5, "размер не тот ($n байт)", f); return }
        if (String(b, 0, 4, Charsets.US_ASCII) != "RIFF" ||
            String(b, 8, 4, Charsets.US_ASCII) != "WAVE"
        ) { trimBail(1, "это не WAV", f); return }

        var off = 12
        var channels = 0
        var sampleRate = 0
        var bits = 0
        var dataOff = -1
        var dataLen = 0
        while (off + 8 <= n) {
            val id = String(b, off, 4, Charsets.US_ASCII)
            val sz = leInt(b, off + 4)
            if (sz < 0 || off + 8 + sz > n) {
                if (id == "data") { dataOff = off + 8; dataLen = n - dataOff }
                break
            }
            if (id == "fmt " && sz >= 16) {
                // msg4409: движки пишут и «расширенный» заголовок
                // (WAVE_FORMAT_EXTENSIBLE, тег 0xFFFE): подформат там лежит
                // GUID'ом, и для обычного PCM он тоже начинается единицей.
                // Раньше принимали только тег 1 — на таком файле обрезка молча
                // ничего не делала.
                val tag = leShort(b, off + 8)
                val pcm = tag == 1 ||
                    (tag == 0xFFFE && sz >= 40 && leInt(b, off + 32) == 1)
                if (!pcm) { trimBail(2, "формат не PCM (тег $tag)", f); return }
                channels = leShort(b, off + 10)
                sampleRate = leInt(b, off + 12)
                bits = leShort(b, off + 22)
            } else if (id == "data") {
                dataOff = off + 8
                dataLen = minOf(sz, n - dataOff)
            }
            off += 8 + sz + (sz and 1)
        }
        if (channels !in 1..2 || bits != 16 || sampleRate !in 8000..48000) {
            trimBail(3, "не тот звук (каналов $channels, бит $bits, Гц $sampleRate)", f)
            return
        }
        if (dataOff < 0 || dataLen < 3200) { trimBail(4, "нет блока data", f); return }

        val frame = channels * 2
        val frames = dataLen / frame
        if (frames < 400) { trimBail(5, "слишком короткий ($frames кадров)", f); return }

        fun ampOf(frameIdx: Int): Int {
            var m = 0
            var i = dataOff + frameIdx * frame
            repeat(channels) {
                val v = ((b[i + 1].toInt() shl 8) or (b[i].toInt() and 0xFF)).toShort().toInt()
                val a = if (v < 0) -v else v
                if (a > m) m = a
                i += 2
            }
            return m
        }

        val thresh = 300 // ≈ −40 dBFS: тише этого считаем тишиной
        val scanCap = minOf(frames, sampleRate * 2)
        var first = -1
        var i = 0
        while (i < scanCap) {
            if (ampOf(i) > thresh) { first = i; break }
            i++
        }
        if (first < 0) { trimBail(7, "сплошная тишина", f); return }
        var last = -1
        var j = frames - 1
        while (j > first) {
            if (ampOf(j) > thresh) { last = j; break }
            j--
        }
        if (last < 0) { trimBail(7, "сплошная тишина", f); return }

        // msg5604: остаток тишины на стыке задаёт настройка — две пятых в
        // голове фразы, три пятых в хвосте (при 130 мс это прежние 50 и 83 мс).
        val keep = pauseKeepMs.coerceIn(0, 1000)
        val headKeep = sampleRate * (keep * 2 / 5) / 1000
        val tailKeep = sampleRate * (keep * 3 / 5) / 1000
        val startF = (first - headKeep).coerceAtLeast(0)
        val endF = (last + 1 + tailKeep).coerceAtMost(frames)
        if (endF - startF < frames / 10) {
            trimBail(8, "после обрезки осталась бы десятая часть", f)
            return
        }

        val cutHead = startF * 1000 / sampleRate
        val cutTail = (frames - endF) * 1000 / sampleRate
        val needTrim = !(cutHead < 40 && cutTail < 60)

        // ---- Выравнивание громкости (26.09.2026) ----
        // Гугловский движок читает тише, multiTTS — громче, и при смене движка
        // это слышно. Считаем среднюю громкость звучащей части (RMS, уже без
        // краевой тишины) и домножаем отсчёты до общей цели: одна громкость у
        // всех движков, голосов и фраз.
        var rmsDb = 0.0
        var gainDb = 0.0
        var gain = 1f
        var peak = 0
        val usedFrames = endF - startF
        if (usedFrames > 0) {
            var sum = 0.0
            var k = startF
            while (k < endF) {
                var at = dataOff + k * frame
                repeat(channels) {
                    val v = ((b[at + 1].toInt() shl 8) or (b[at].toInt() and 0xFF)).toShort().toInt()
                    sum += v.toDouble() * v
                    val a = if (v < 0) -v else v
                    if (a > peak) peak = a
                    at += 2
                }
                k++
            }
            val rms = kotlin.math.sqrt(sum / (usedFrames * channels))
            if (rms >= 1.0 && peak > 0) {
                rmsDb = 20.0 * kotlin.math.log10(rms / 32768.0)
                gain = (loudTargetRms / rms).toFloat()
                // Не тянем тихое вчетверо и не глушим громкое вчетверо: дальше
                // это уже не выравнивание, а порча звука.
                gain = gain.coerceIn(0.25f, 4f)
                // Пики важнее цели: лучше чуть тише, чем хрип на громких звуках.
                val room = (32767f * 0.98f) / peak
                if (gain > room) gain = room
                if (kotlin.math.abs(gain - 1f) < 0.02f) gain = 1f
                gainDb = 20.0 * kotlin.math.log10(gain.toDouble())
            }
        }

        // ---- Ручная подстройка выше 100% (26.09.2026) ----
        // Ползунок громкости пускает до 200%, но плеер громче единицы не умеет.
        // Значит всё, что выше, домножаем здесь, в самом звуке: так тихий движок
        // (гугловский) можно именно ПОДНЯТЬ, а не только убавить громкий.
        val userVol = if (role == Pending.Role.REPLY) replyVolume else volume
        if (userVol > 1f && peak > 0) {
            gain *= userVol
            val room = (32767f * 0.98f) / peak
            if (gain > room) gain = room
            gainDb = 20.0 * kotlin.math.log10(gain.toDouble())
        }

        if (!needTrim && gain == 1f) {
            // Ни тишины по краям, ни разницы в громкости — файл не трогаем.
            trimBail(9, "тишины по краям нет (голова $cutHead мс, хвост $cutTail мс)", f)
            return
        }

        val outLen = (endF - startF) * frame
        val out = ByteArray(44 + outLen)
        System.arraycopy("RIFF".toByteArray(Charsets.US_ASCII), 0, out, 0, 4)
        System.arraycopy("WAVE".toByteArray(Charsets.US_ASCII), 0, out, 8, 4)
        System.arraycopy("fmt ".toByteArray(Charsets.US_ASCII), 0, out, 12, 4)
        System.arraycopy("data".toByteArray(Charsets.US_ASCII), 0, out, 36, 4)
        val putInt = { at: Int, v: Int ->
            out[at] = (v and 0xFF).toByte()
            out[at + 1] = ((v shr 8) and 0xFF).toByte()
            out[at + 2] = ((v shr 16) and 0xFF).toByte()
            out[at + 3] = ((v shr 24) and 0xFF).toByte()
        }
        val putShort = { at: Int, v: Int ->
            out[at] = (v and 0xFF).toByte()
            out[at + 1] = ((v shr 8) and 0xFF).toByte()
        }
        putInt(4, 36 + outLen)
        putInt(16, 16)
        putShort(20, 1)
        putShort(22, channels)
        putInt(24, sampleRate)
        putInt(28, sampleRate * frame)
        putShort(32, frame)
        putShort(34, 16)
        putInt(40, outLen)
        System.arraycopy(b, dataOff + startF * frame, out, 44, outLen)

        // Домножаем отсчёты на выравнивающий коэффициент (16 бит, little-endian).
        if (gain != 1f) {
            var at = 44
            val end = 44 + outLen - 1
            while (at < end) {
                val v = ((out[at + 1].toInt() shl 8) or (out[at].toInt() and 0xFF)).toShort().toInt()
                var s = (v * gain).toInt()
                if (s > 32767) s = 32767
                if (s < -32768) s = -32768
                out[at] = (s and 0xFF).toByte()
                out[at + 1] = ((s shr 8) and 0xFF).toByte()
                at += 2
            }
        }

        if (!runCatching { f.writeBytes(out) }.isSuccess) return
        // В журнал — сколько тишины движок дописал ВСЕГО и сколько из неё
        // срезано: по этой строке видно, из чего состояла пауза между
        // предложениями (msg4409: «на слух ничего не меняет» — вот цифры).
        // Плюс громкость: измеренная и сдвиг — по ним видно выравнивание.
        val silHead = first * 1000 / sampleRate
        val silTail = (frames - 1 - last) * 1000 / sampleRate
        Diag.log(
            appContext, "sound",
            "паузы: у ${f.name} [$trimWho] тишины было ${silHead} мс в начале и ${silTail} мс в конце; " +
                "срезано ${cutHead} и ${cutTail} мс; громкость ${fmtDb(rmsDb)} dBFS, сдвиг ${fmtDb(gainDb)} dB"
        )
    }

    /** Децибелы с одним знаком для журнала (точка, а не запятая: журнал читают
     *  скриптом и глазами). */
    private fun fmtDb(v: Double): String = String.format(java.util.Locale.US, "%.1f", v)

    // ---------------- Файлы играет ExoPlayer ----------------

    /** Играет ли сейчас наш звук — по состоянию ExoPlayer. Все сторожа
     *  спрашивают здесь. */
    private fun soundPlaying(): Boolean = exoFilePlayingSafe()

    // Сторож замершей позиции: пока позиция НИ РАЗУ не росла — не судим (на
    // части прошивок currentPosition всегда ноль, и мы бы рвали фразы на ровном
    // месте); увидели рост, а потом позиция встала на три проверки подряд —
    // фразу считаем потерянной и говорим её напрямую движком, иначе чтение
    // замолчит навсегда.
    private var exoPosToken = 0
    private var exoPosLast = -1L
    private var exoPosSawProgress = false
    private var exoPosStuckHits = 0
    private val exoPosCheck = object : Runnable {
        override fun run() {
            if (!exoFilePlayingSafe()) return
            val pos = runCatching { filePlayer.positionMs }.getOrDefault(-1L)
            if (pos > exoPosLast) {
                exoPosSawProgress = true
                exoPosStuckHits = 0
            } else if (exoPosSawProgress) {
                if (++exoPosStuckHits >= EXO_POS_STUCK_HITS) {
                    exoPosStuckHits = 0
                    Diag.log(
                        appContext, "sound",
                        "exo: позиция стоит ${EXO_POS_STUCK_HITS * EXO_POS_STEP_MS / 1000} с — " +
                            "фраза потерялась, говорю напрямую",
                    )
                    fallbackDirect(currentText)
                    return
                }
            }
            exoPosLast = pos
            main.postDelayed(this, EXO_POS_STEP_MS)
        }
    }

    /** Взвести сторож позиции заново — на каждой новой фразе: у неё своя позиция. */
    private fun armExoPositionWatch() {
        val token = ++exoPosToken
        exoPosLast = -1L
        exoPosSawProgress = false
        exoPosStuckHits = 0
        main.removeCallbacks(exoPosCheck)
        main.postDelayed(exoPosCheck, EXO_POS_STEP_MS)
        // Токен нужен только чтобы старый экземпляр проверки не ожил после
        // остановки: releaseMedia его увеличивает.
        if (token < 0) exoPosToken = 0
    }

    /** Снять сторож позиции (звук погашен или пошёл напрямую). */
    private fun dropExoPositionWatch() {
        exoPosToken++
        exoPosStuckHits = 0
        exoPosSawProgress = false
        exoPosLast = -1L
        main.removeCallbacks(exoPosCheck)
    }

    /** Начать играть фразу новым плеером. [positionMs] — продолжение паузы с
     *  середины файла: у ExoPlayer позиция точная, переигрывать начало не нужно. */
    private fun exoPlay(text: String, f: File, rate: Float, positionMs: Long = 0L) {
        // 29.09.2026 (потеря текста в 187): если звук УЖЕ идёт, список не
        // перезапускаем — фразу ДОПИСЫВАЕМ за звучащей. Перезапуск выбрасывал всё,
        // что стояло впереди, и плеер прыгал через несколько фраз.
        if (positionMs == 0L && exoFilePlayingSafe() && playingText != null && exoPending.isNotEmpty()) {
            exoAppend(text, f, rate)
            return
        }
        playingText = text
        playingFile = f
        playingRate = rate
        exoAhead = 0
        exoPending.clear()
        exoPending.addLast(Prepared(text, f, rate, roleOfFile(f)))
        filePlayer.setListener(exoListener)
        exoSyncSpeed(exoPending.last())
        filePlayer.setVolume(volumeFor(f))
        filePlayer.play(
            listOf(FilePlayback.Item(id = ++exoSeq, text = text, file = f)),
            startIndex = 0,
            startPositionMs = positionMs,
        )
        armExoStartWatch(text)
        armSoundWatch()
        exoTopUp()
    }

    /** Фраза от читалки в новом пути. Правила: звучит сейчас — не трогаем; уже
     *  стоит впереди в списке — ждём её (список НЕ перезапускаем, иначе гибнет всё,
     *  что впереди, — это и была потеря текста в 187); в списке нет — выбрасываем
     *  хвост и дописываем эту фразу за звучащей. */
    private fun speakExo(text: String) {
        // 29.09.2026: слушателя ставим ЗДЕСЬ, при каждом обращении чтения. В 190
        // его ставили только в exoPlay (когда список начинается заново), а если
        // фраза уже лежала в списке (подготовили заранее) — плеер пускали без
        // слушателя, и «фраза доиграла» до чтения не доходила: чтение вставало.
        filePlayer.setListener(exoListener)
        // 30.09.2026: вместе с фразой взводим сторож звука — если она так и не
        // зазвучит (мёртвый список плеера после ошибки файла), чтение не замолчит.
        armSoundWatch()
        // 1) эта фраза звучит прямо сейчас
        if (playingText == text && exoFilePlayingSafe()) {
            Diag.log(appContext, "sound", "exo: эта фраза уже звучит — очередь не трогаю")
            requestPrefetch()
            exoTopUp()
            return
        }
        // 2) она уже впереди в списке плеера — просто ждём
        if (exoPending.any { it.text == text }) {
            Diag.log(appContext, "sound", "exo: фраза уже впереди в списке — жду её")
            // 29.09.2026: после паузы или после подготовки первой фразы плеер
            // стоит молча — «продолжить» должно его просто пустить (жалоба Сержа:
            // «ставлю на паузу, нажимаю воспроизвести, а он молчит»).
            if (!exoFilePlayingSafe()) {
                runCatching { filePlayer.resume() }
                Diag.log(appContext, "sound", "exo: пускаю список (был на паузе)")
            }
            requestPrefetch()
            exoTopUp()
            return
        }
        // 3) её в списке нет: хвост вон (звучащую не трогаем), эту — за звучащей
        exoDropTail()
        // 3а) пауза сохранила звук ровно этой фразы — продолжаем с того места
        takeKeptPhrase(text)?.let { kept ->
            exoPlay(kept.text, kept.file, kept.rate, keptPositionMs)
            return
        }
        // 3б) фраза в очереди, но не первая: всё перед ней чтение уже прошло
        // (прыжок вперёд) — выбрасываем и играем её. Без этого мы бы заказали её
        // заново и услышали в другой раз (30.09.2026).
        val deeper = readyQueue.indexOfFirst { it.text == text && it.rate == rateFor(it.role) }
        if (deeper > 0) {
            repeat(deeper) { runCatching { readyQueue.removeFirst().file.delete() } }
        }
        val head = readyQueue.firstOrNull()
        if (head != null && head.text == text && head.rate == rateFor(head.role)) {
            readyQueue.removeFirst()
            awaitingPlayText = null
            exoPlay(text, head.file, head.rate)
            requestPrefetch()
            return
        }
        if (prefetchInFlight.contains(text)) {
            // Заявка уже в пути: ждём её, файл придёт в synthFinished.
            awaitingPlayText = text
            return
        }
        awaitingPlayText = text
        synthToFile(text)
    }

    /** Дописать одну фразу в конец списка плеера (с записью в зеркало). */
    private fun exoAppend(text: String, f: File, rate: Float) {
        // 29.09.2026, жалоба Сержа «одна фраза прочиталась три раза» (журнал
        // 17:40:57): на старте чтения читалка успевала ответить на заказ дважды
        // по-разному — сначала одной фразой, потом другой, — сверка конвейера
        // выбрасывала хвост и заказывала заново, а копии УЖЕ дописанных в плеер
        // фраз оставались в списке и звучали подряд. Сверку это не лечит (её
        // причину убрали отдельно), но услышать одну фразу дважды мы не должны
        // ни при каком раскладе: ту же фразу второй раз в список не берём.
        val same = exoPending.firstOrNull { it.text == text }
        if (same != null && same.rate == rate) {
            runCatching { f.delete() }
            Diag.log(appContext, "sound", "exo: такая фраза уже есть в списке — лишнюю не беру (${f.name})")
            return
        }
        if (same != null) {
            // Та же фраза, но сделанная на прежней скорости (или прежним голосом):
            // она устарела — выбрасываем хвост списка и берём свежую.
            Diag.log(
                appContext, "sound",
                "exo: фраза в списке сделана на скорости ${same.rate}, а нужна $rate — беру свежую"
            )
            exoDropTail()
        }
        if (text == playingText) {
            runCatching { f.delete() }
            Diag.log(appContext, "sound", "exo: эта фраза уже звучит — лишнюю не беру (${f.name})")
            return
        }
        exoPending.addLast(Prepared(text, f, rate, roleOfFile(f)))
        filePlayer.append(listOf(FilePlayback.Item(id = ++exoSeq, text = text, file = f)))
        Diag.log(appContext, "sound", "exo: дописал фразу (${f.name}), впереди ${exoPending.size - 1}")
    }

    /** Файл [p] уже сделан движком на скорости [Prepared.rate] — плееру задаём
     *  только отношение «нужная скорость / темп файла». Обычно это ровно 1.0:
     *  файл свежий. Не 1.0 бывает, когда ползунок двинули на ходу (тогда звучащий
     *  файл дотягивается до нового темпа) или
     *  когда в списке лежит заготовка прежней скорости. */
    private fun exoSyncSpeed(p: Prepared) {
        val fileRate = if (p.rate > 0f) p.rate else 1f
        exoPlayingRate = fileRate
        val want = rateFor(p.role)
        val ratio = (want / fileRate).coerceIn(0.25f, 4f)
        runCatching { filePlayer.setSpeed(ratio) }
        // Тон доводим так же, как темп: файл записан движком на [pitchFor] своего
        // времени, а звучать должен на нынешнем ползунке (29.09.2026).
        val madeAt = filePitchOf(p.file)
        exoPlayingPitch = if (madeAt > 0f) madeAt else 1f
        val pitchRatio = (pitchFor(p.role) / exoPlayingPitch).coerceIn(0.25f, 4f)
        runCatching { filePlayer.setPitch(pitchRatio) }
    }

    /** Выбросить из списка всё, что ещё не звучало (звучащую фразу не трогаем) —
     *  так уходят неверные заготовки, не обрывая речь. */
    private fun exoDropTail() {
        if (exoPending.size <= 1) return
        val keep = exoPending.first()
        while (exoPending.size > 1) {
            val dropped = exoPending.removeLast()
            runCatching { dropped.file.delete() }
        }
        exoAhead = 0
        runCatching { filePlayer.dropAhead(0) }
        Diag.log(appContext, "sound", "exo: хвост выброшен, оставил «${keep.file.name}»")
    }

    /** Дописать в список заготовки из [readyQueue] — это замена прицепке встык:
     *  у ExoPlayer очередь настоящая, и впереди может стоять сколько угодно фраз. */
    private fun exoTopUp() {
        var appended = 0
        // 30.09.2026, жалоба Сержа «были похожие фразы, и одна прочиталась дважды»
        // (журнал 15:17:02): книгу читает один движок, реплики — второй, и заявки
        // они выполняют с разной скоростью. Фразы уходили в плеер в порядке
        // ГОТОВНОСТИ: соседние «такая ты сладкая!» (книга, готова быстро) и
        // «- Я бы тебя съел...» (реплика, готовилась дольше) вставали в списке
        // наоборот, и слушатель слышал их переставленными. Хуже: пауза сохраняла
        // звучащую (реплика), а чтение уже стояло на следующей фразе — после
        // «продолжить» та же фраза звучала ВТОРОЙ раз.
        // Теперь фразу, заказанную позже той, что ещё в работе, держим в очереди:
        // порядок заказа = порядок звучания (см. [Prepared.req]).
        val earliest = earliestInFlight()
        // Одна фраза звучит, [prefetchDepth] - 1 держим впереди — считаем по
        // зеркалу: очередь заготовок к этому моменту уже опустела, фразы ушли в плеер.
        while (exoPending.size - 1 < prefetchDepth - 1 && readyQueue.isNotEmpty()) {
            val head = readyQueue.first()
            if (earliest != null && head.req != 0L && head.req > earliest) {
                if (heldForOrderLogged != head.req) {
                    heldForOrderLogged = head.req
                    Diag.log(
                        appContext, "sound",
                        "exo: держу фразу (${head.file.name}) «${FilePlayback.brief(head.text)}» — " +
                            "раньше неё заказана другая, жду её"
                    )
                }
                break
            }
            readyQueue.removeFirst()
            exoAppend(head.text, head.file, head.rate)
            appended++
        }
        if (appended > 0) {
            Diag.log(appContext, "sound", "exo: дописал заготовок $appended (впереди ${exoPending.size - 1})")
        }
    }

    /** Положить готовую фразу в очередь НА СВОЁ место — по номеру заявки.
     *
     *  30.09.2026, журнал 215 (15:30:18-15:30:25): простого «держу фразу» оказалось
     *  мало. Книжную фразу (s_5, предл. 1175) движок отдал раньше, чем реплику
     *  (s_4, предл. 1174), её придержали — а когда реплика доспела, она встала в
     *  КОНЕЦ очереди, то есть ПОСЛЕ придержанной. На слух вышло: сначала «Мы сейчас
     *  ме-е-едленно…» (1175), потом «- Нет.» (1174), а затем чтение, дойдя до 1175,
     *  заказало эту фразу заново и она прозвучала ВТОРОЙ раз (s_9). Порядок в
     *  очереди теперь держится по номеру заявки, а не по времени готовности. */
    private fun addReadyInOrder(p: Prepared) {
        if (p.req == 0L) {
            readyQueue.addLast(p)
            return
        }
        val at = readyQueue.indexOfFirst { it.req != 0L && it.req > p.req }
        if (at < 0) readyQueue.addLast(p) else readyQueue.add(at, p)
    }

    /** О какой фразе уже сказали «держу» — чтобы не повторять строку в журнале. */
    private var heldForOrderLogged = 0L

    /** Самая ранняя заявка, которая ещё в работе (файл не пришёл). Если такой
     *  нет — отдавать плееру можно всё. */
    private fun earliestInFlight(): Long? =
        pending.entries.filter { it.value.kind == Pending.Kind.FILE }.minOfOrNull { it.key }

    /** Сторож «звук не начался»: молчание лечим прямой речью. */
    private fun armExoStartWatch(text: String) {
        val token = ++exoStartToken
        main.postDelayed({
            if (token != exoStartToken) return@postDelayed
            if (!exoFilePlayingSafe()) {
                Diag.log(appContext, "sound", "exo: звук не начался — говорю фразу напрямую")
                // 30.09.2026: заминка — в память окна «Не засыпать» (StallLog).
                StallLog.record(appContext, "фраза не зазвучала за ${PLAY_STALL_MS / 1000} с")
                fallbackDirect(text)
            }
        }, PLAY_STALL_MS)
    }

    /** Сторож «звука нет, а читать должны».
     *
     *  30.09.2026, журнал 00:47:29 (жалоба Сержа «остановилось чтение»): после
     *  ошибки файла список плеера оставался мёртвым — в нём шесть фраз, часть уже
     *  удалена, — и новые в него не дописывались: очередь заготовок ждала места
     *  (см. [exoTopUp]), места не появлялось, «фраза доиграла» не приходила.
     *  Снаружи это вечная тишина, а приложение считает, что читает («power:
     *  бьюсь: чтение идёт»). Сторож взводится на каждое обращение чтения и
     *  снимается, когда фраза зазвучала: если за [SOUND_STALL_MS] ни одна не
     *  началась, а фразы есть — выбрасываем список и играем следующую готовую
     *  (или собираем заново). Пока идёт синтез, сторож молчит: это нормальное
     *  ожидание, а не тупик. */
    private fun armSoundWatch() {
        val token = ++soundWatchToken
        main.postDelayed({
            if (token != soundWatchToken) return@postDelayed
            if (exoFilePlayingSafe()) {
                armSoundWatch()
                return@postDelayed
            }
            if (pending.values.any { it.kind == Pending.Kind.FILE }) {
                // Синтез в работе — ждём его, тупика нет.
                armSoundWatch()
                return@postDelayed
            }
            val next = readyQueue.firstOrNull()
            if (next == null && exoPending.isEmpty()) {
                // Просить нечего: чтение встало или на паузе — сторож не нужен.
                return@postDelayed
            }
            Diag.log(
                appContext, "sound",
                "звука нет ${SOUND_STALL_MS / 1000} с, а фразы есть (готовых ${readyQueue.size}, " +
                    "в списке плеера ${exoPending.size}) — выбрасываю список и играю дальше"
            )
            // 30.09.2026: самая честная заминка «читаем, а звука нет» — в память
            // окна «Не засыпать» (StallLog): по ней видно, часто ли это вообще.
            StallLog.record(appContext, "звука не было ${SOUND_STALL_MS / 1000} с, хотя фразы были")
            exoClearAll()
            if (next != null) {
                readyQueue.removeFirst()
                awaitingPlayText = null
                exoPlay(next.text, next.file, next.rate)
            } else {
                val t = awaitingPlayText ?: currentText
                if (!t.isNullOrBlank()) {
                    awaitingPlayText = t
                    synthToFile(t)
                }
            }
            armSoundWatch()
        }, SOUND_STALL_MS)
    }

    /** Снять сторож звука: фраза зазвучала или чтение встало. */
    private fun dropSoundWatch() {
        soundWatchToken++
    }

    private fun exoFilePlayingSafe(): Boolean = runCatching { filePlayer.isPlaying }.getOrDefault(false)

    /** Что сообщает плеер: «фраза доиграла» двигает чтение, ошибка уходит в
     *  прямую речь. */
    private val exoListener = object : FilePlayback.Listener {
        override fun onPhraseStart(index: Int, item: FilePlayback.Item) {
            exoStartToken++ // звук пошёл — сторож старта больше не нужен
            dropSoundWatch() // и сторож «звука нет» тоже: фраза зазвучала
            playingText = item.text
            playingFile = item.file
            // Громкость у реплик своя: файл мог прийти от второго движка.
            filePlayer.setVolume(volumeFor(item.file))
            // Темп у каждой фразы свой: файл сделан на [Prepared.rate], а звучать
            // должен на нынешней скорости ползунка (см. [exoSyncSpeed]). Заодно
            // запоминаем темп САМОГО ФАЙЛА: пауза по нему проверяет, годится ли
            // сохранённый звук для продолжения (см. [pauseKeepingPhrase]).
            //
            // 29.09.2026 (журнал 21:49, жалоба Сержа «фраза повторилась»): раньше
            // playingRate выставлялся только в [exoPlay], то есть у фраз, которыми
            // список НАЧИНАЛИ. Фразы, доигранные из очереди, оставляли чужой темп —
            // и пауза, сравнив его с нужным, решала, что сохранённый звук «прежней
            // скорости», выбрасывала файл. Продолжение синтезировалось заново и
            // звучало С НАЧАЛА: на слух это тот самый повтор.
            exoPending.firstOrNull { it.file.name == item.file.name }?.let { p ->
                playingRate = p.rate
                exoSyncSpeed(p)
            }
            // Фраза новая — позиция у неё своя: сторож взводим заново.
            armExoPositionWatch()
        }

        override fun onPhraseEnd(index: Int, item: FilePlayback.Item) {
            if (exoAhead > 0) exoAhead--
            // Фраза ушла из зеркала: она больше не «впереди».
            if (exoPending.isNotEmpty() && exoPending.first().text == item.text) exoPending.removeFirst()
            dropExoPositionWatch() // фраза кончилась — сторожить её позицию больше нечего
            Diag.log(
                appContext, "sound",
                "фраза доиграла: ${item.file.name} «${FilePlayback.brief(item.text)}»",
            )
            runCatching { item.file.delete() }
            playingText = null
            playingFile = null
            rescueText = null
            rescueTries = 0
            retriesInRow = 0
            // Порядок как в прежнем пути: сперва наполняем очередь, потом двигаем
            // чтение — иначе оно попросит фразу, которой ещё нет.
            requestPrefetch()
            exoTopUp()
            onDone?.invoke()
        }

        override fun onAllEnded() {
            Diag.log(appContext, "sound", "exo: список кончился — жду следующую фразу")
            // 29.09.2026: подстраховка от вечного молчания. Если «фраза доиграла»
            // по списку не пришла (в 190 так и вышло — слушателя забыли поставить),
            // здесь сами считаем фразу законченной: двигаем чтение и заказываем
            // заготовки. Молчание навсегда недопустимо.
            if (playingText != null) {
                Diag.log(appContext, "sound", "exo: конца фразы не дождались — двигаю чтение сам")
                playingText = null
                playingFile = null
                exoPending.clear()
                exoAhead = 0
                requestPrefetch()
                exoTopUp()
                onDone?.invoke()
            }
        }

        override fun onError(item: FilePlayback.Item?, message: String) {
            val text = item?.text ?: currentText
            item?.file?.delete()
            Diag.log(
                appContext, "sound",
                "exo: файл не заиграл ($message) — чищу список и собираю фразу заново «${FilePlayback.brief(text ?: "")}»"
            )
            // 30.09.2026 (журнал 00:47:29, жалоба Сержа «остановилось чтение»):
            // прежде здесь произносили фразу НАПРЯМУЮ движком, а список плеера
            // оставляли как был — с уже удалёнными файлами. Дальше очередь
            // заготовок ждала в нём места, места не появлялось, «фраза доиграла»
            // не приходила, и чтение замолкало насовсем. Плюс та прямая речь идёт
            // своим уровнем и звучит громче выровненных файлов — Серж услышал это
            // как «громкость скакнула вверх». Теперь чистим состояние плеера
            // целиком и собираем ту же фразу заново — обычным путём, через файл.
            exoClearAll()
            if (text.isNullOrBlank()) {
                onDone?.invoke()
                return
            }
            awaitingPlayText = text
            synthToFile(text)
            armExoStartWatch(text)
            armSoundWatch()
        }
    }

    /** Сыграть готовый файл. [rate] — скорость, которой он сделан: её храним
     *  вместе с играющим файлом, чтобы пауза не выдала прежний темп за текущий
     *  (см. [pauseKeepingPhrase]). */
    private fun playFile(f: File, rate: Float = speed) {
        val t = currentText ?: return
        exoPlay(t, f, rate)
    }

    /** Выбросить всё, что заготовлено впрок (msg5604). Зовётся, когда на ходу
     *  сменили голос или движок: заготовки сделаны ПРЕЖНИМ голосом, и пока они
     *  не отыграют (до трёх в очереди), новый голос не слышен вовсе. Заодно
     *  снимаем метку «синтез идёт»: файл, который доспеет после смены, уже
     *  осиротеет и будет удалён — он тоже прежним голосом. Текущий звук не
     *  трогаем: его перечитает читалка ([ReaderEngine] restartAfterSwitch). */
    fun dropPrepared() {
        prefetchInFlight.clear()
        awaitingPlayText = null
        prewarmOnly = false
        // Голос сменился — сохранённый паузой звук сделан прежним.
        keptPhrase?.let { runCatching { it.file.delete() } }
        keptPhrase = null
        clearPrefetch()
        // 29.09.2026 (журнал 18:04, «смена голоса на ходу»): в новом пути заготовки
        // лежат в списке плеера, и без этой чистки после смены голоса продолжали
        // звучать файлы ПРЕЖНЕГО голоса — Серж описал это как «переключаю, а он
        // читает старым». Список чистим целиком, вместе со звучащей фразой: её
        // чтение перечитает уже новым голосом ([restartAfterSwitch]).
        exoClearAll()
        // 30.09.2026 (сборка 228). В ПРЯМОМ чтении файлов нет вовсе, и чистка
        // списка плеера ничего не даёт: звук идёт из очереди САМОГО движка, и она
        // продолжала играть прежним голосом. В журнале Сержа 11:38:02 так и
        // вышло: голос применился, читалка попросила фразу заново, а мы ответили
        // «эта фраза уже звучит — очередь не трогаю», и старый голос дочитывал
        // текущую фразу и ещё две заготовки. Серж: «дочитывает кусочек, и потом
        // только перескакивает — нужно, чтобы мгновенно». Теперь очередь движка
        // обрывается тут же.
        cutDirectNow("смена голоса на ходу")
    }

    /** Оборвать прямую речь прямо сейчас: движок перестаёт говорить, его очередь
     *  и наши заявки выбрасываются (30.09.2026, сборка 228).
     *
     *  Зачем отдельно от [stop]. [stop] — это пауза: он ещё и отпускает плеер,
     *  снимает надзоры, чистит сохранённую паузой фразу. Здесь нужно ровно одно:
     *  чтобы движок замолчал и его очередь не доигрывала прежним голосом, пока
     *  читалка заказывает ту же фразу заново. */
    private fun cutDirectNow(reason: String) {
        if (!directMode) return
        val wasQueue = directQueue.size
        val wasSpeaking = directSpeakingText != null
        if (wasQueue == 0 && !wasSpeaking) return
        flushDirectQueue(reason)
        // Движок мог говорить и без нашей очереди (заявка уже доигрывала):
        // гасим его самого, очередь у него при этом выметается целиком.
        runCatching { tts?.stop() }
        runCatching { replyTts?.stop() }
        directSpeakingText = null
        directAskedId = null
        Diag.log(
            appContext, "tts",
            "прямая речь оборвана ($reason): в очереди было $wasQueue, звучала=$wasSpeaking",
        )
    }

    /** Погасить список плеера целиком: ничего не остаётся ни звучать, ни ждать. */
    private fun exoClearAll() {
        exoPending.clear()
        exoAhead = 0
        playingText = null
        playingFile = null
        dropExoPositionWatch()
        exoStartToken++
        runCatching { filePlayer.stop() }
    }

    /** Чей голос сделал этот файл: репликовый или книжный. Файлы реплик мы и
     *  так помним по имени (см. [replyFiles]), а знать роль нужно затем, что от
     *  неё зависят и скорость заготовки, и громкость звука. */
    private fun roleOfFile(f: File): Pending.Role =
        if (f.name in replyFiles) Pending.Role.REPLY else Pending.Role.MAIN

    /** Собственный аудиоплеер не смог сыграть файл (редкий случай) — чтобы
     *  чтение не замолчало, произносим текст напрямую движком. На время этой
     *  фразы media-кнопки будут не наши; по её окончании чтение продолжается. */
    private fun fallbackDirect(text: String?) {
        if (text.isNullOrBlank()) return
        val t = tts
        if (t == null || !ready) {
            // Совсем ничего не вышло — пропускаем предложение, чтение не встаёт.
            onDone?.invoke()
            return
        }
        val id = reqSeq++
        pending[id] = Pending(Pending.Kind.DIRECT, text, null)
        val r = runCatching { t.speak(Roles.stripped(text), TextToSpeech.QUEUE_FLUSH, null, id.toString()) }
            .getOrDefault(TextToSpeech.ERROR)
        if (r != TextToSpeech.SUCCESS) {
            pending.remove(id)
            onDone?.invoke()
        } else {
            armDirectWatch(id)
        }
    }

    /** Отменить текущее проигрывание. onDone НЕ вызывается. */
    private fun releaseMedia() {
        dropSoundWatch() // чтение встало — сторож «звука нет» больше не нужен
        playingText = null
        playingFile = null
        // У ExoPlayer отпускаем его список целиком.
        exoStartToken++
        exoAhead = 0
        // 29.09.2026: зеркало тоже чистим. Иначе после паузы оно врало, что
        // фразы «ещё впереди в списке», и «продолжить» молчало (жалоба Сержа).
        exoPending.clear()
        dropExoPositionWatch()
        runCatching { filePlayer.stop() }
    }

    /** Пока играет текущее — спросить читалку, какие фразы будут следующими, и
     *  синтезировать их заранее, чтобы между фразами не было паузы.
     *
     *  msg4472: держим [prefetchDepth] фраз готовыми.
     *
     *  29.09.2026 (просьба Сержа: «можем ли мы три фразы одновременно
     *  синтезировать»): заявок в работе теперь столько, сколько мест в очереди
     *  ([maxInFlight]), а не одна. Заказываем сразу весь набор — движок сам
     *  решает, делать их подряд или параллельно; у сетевых голосов он умеет
     *  параллельно, и тогда три файла приходят за время одного. Раньше заказ
     *  уходил только после ответа на предыдущий, и очередь наполнялась по одной.
     *  У локального движка по-прежнему одна заявка за раз ([maxInFlight]). */
    private fun requestPrefetch() {
        if (directMode) return // заготовки не нужны: движок читает сам
        if (awaitingPlayText != null) return // текущая фраза ещё не сыграна
        // 29.09.2026 (журнал 17:53): у ExoPlayer фразы из очереди заготовок уезжают
        // в список плеера ([exoTopUp]) и в очереди больше не числятся. В позицию
        // заказа их тоже надо считать: иначе читалку спрашивают про уже заказанные
        // фразы, она называет то, что в списке уже стоит, и каждый круг в журнале
        // «exo: такая фраза уже есть в списке — лишнюю не беру». Само чтение от
        // этого не рвётся, но очередь наполняется наполовину и бессмысленно.
        val inPlayer = (exoPending.size - 1).coerceAtLeast(0)
        var issued = 0
        // 29.09.2026, НАЙДЕНО ПО ЖУРНАЛУ 10:24 («программа не отвечает» на смене
        // скорости): в условии стояло число заявок, снятое ДО цикла (`inFlight`),
        // а позиция считалась по живому набору. Как только очередь и набор пусты
        // (смена скорости их чистит — [dropStaleRate]), условие «0 + 0 + 0 < 3»
        // выполнялось ВЕЧНО, и цикл заказывал синтез фразы за фразой, пока читалка
        // не откажется называть следующую: в журнале это «позиция 126 из 3», то
        // есть 126 заявок в одном вызове. Дальше сверка конвейера обходила все
        // 126 заявок, и на КАЖДУЮ читалка считала фразу от текущего места (с
        // применением словаря) — квадратичная работа на главном потоке, движок
        // захлёбывался сотней заявок, окно переставало отвечать. Теперь условие
        // считает ЖИВЫЕ числа: заявок ровно столько, сколько не хватает до глубины.
        while (readyQueue.size + prefetchInFlight.size + inPlayer < prefetchDepth) {
            if (issued >= prefetchDepth) break // страховка: больше глубины не заказываем
            val offset = inPlayer + readyQueue.size + prefetchInFlight.size + 1
            // 29.09.2026: в журнал — почему очередь НЕ растёт. Жалоба Сержа: с
            // сетевым синтезатором паузы стали меньше, но остались; в журнале
            // видно, что каждая заготовка встаёт «в очереди 1/3», то есть цепочка
            // обрывается, а по чему — из журнала не понять. Причина называется
            // словами, и повод пишется один раз на вид (не спамим).
            val next = onNeedNext?.invoke(offset) ?: return logPrefetchSkip(offset, "чтение не назвало фразу")
            if (next.isBlank()) return logPrefetchSkip(offset, "фраза пустая")
            if (next == currentText) return logPrefetchSkip(offset, "эта фраза уже звучит")
            if (readyQueue.any { it.text == next }) return logPrefetchSkip(offset, "фраза уже в очереди")
            if (prefetchInFlight.contains(next)) return logPrefetchSkip(offset, "фраза уже в работе")
            prefetchInFlight.add(next)
            synthToFile(next)
            issued++
        }
        // 29.09.2026: в журнал — сколько заявок ушло движку разом. По этой строке
        // видно и глубину конвейера, и то, делает ли движок их параллельно:
        // если три файла приходят почти одновременно — параллельно, если по
        // очереди с равными промежутками — значит он их сериализует.
        if (issued > 0) {
            Diag.log(
                appContext, "sound",
                "заказал заготовок: $issued (в работе ${prefetchInFlight.size} из $maxInFlight)"
            )
        }
    }

    /** Почему заготовка вперёд не заказана — в журнал (29.09.2026). Пишем по
     *  разу на повод: чтение идёт минутами, и повторять одну и ту же строку
     *  каждый раз незачем. */
    private val prefetchSkipsLogged = HashSet<String>()

    private fun logPrefetchSkip(offset: Int, why: String) {
        if (!prefetchSkipsLogged.add(why)) return
        Diag.log(
            appContext, "sound",
            "заготовку вперёд не заказываю (позиция $offset из $prefetchDepth): $why"
        )
    }

    /** Полностью обнулить состояние пайплайна (без остановки TTS). */
    private fun resetPipeline() {
        forgetAllSynthWatches()
        directWatchToken++
        awaitingPlayText = null
        prefetchInFlight.clear()
        prewarmOnly = false
        synthMisses.clear()
        directQueue.clear()
        directWaitReply = false
        directAskedId = null
        directSpeakingText = null
        lastDirectQueuedId = null
        forgetReplyWait()
        clearPrefetch()
        releaseMedia()
        currentText = null
    }

    private fun clearPrefetch() {
        readyQueue.forEach { runCatching { it.file.delete() } }
        readyQueue.clear()
        // Заявки, которые ещё в пути, тоже снимаем: иначе их файлы приедут
        // позже и попадут в очередь как заготовки для фраз, которых чтение уже
        // не ждёт (при нескольких заявках в работе это стало заметнее).
        if (prefetchInFlight.isNotEmpty()) {
            val drop = HashSet(prefetchInFlight)
            prefetchInFlight.clear()
            pending.entries.removeAll { (_, p) ->
                if (p.kind == Pending.Kind.FILE && drop.contains(p.text)) {
                    p.cancelled = true
                    runCatching { p.file?.delete() }
                    true
                } else {
                    false
                }
            }
        }
    }

    // ---------- Первая фраза заранее и пауза без повторного синтеза ----------
    // (24.09.2026, просьба Сергея: «чтение начиналось бы быстрее»)

    /** Приготовить звук фразы, с которой начнётся чтение, ДО нажатия «читать».
     *
     *  Зачем. Единственная задержка перед первым звуком — синтез первой фразы:
     *  по журналу Сергея это 0,54 с на фразу в 10,6 с речи (движок берёт
     *  40–50 мс на секунду звука), плюс 0,03 с на запуск нашего плеера. Отсюда
     *  и 0,58 с между «читать» и звуком; убрать их можно только тем, что файл
     *  готов заранее — окно читалки открывается на нужном месте за секунды до
     *  нажатия. Это ровно та же заготовка, что и во время чтения, только
     *  заказанная раньше.
     *
     *  Готовим ОДНУ фразу ([prewarmOnly]) и только когда ничего не читается:
     *  очередь впрок без звука — это лишняя работа процессора. Не пригодилась
     *  (прыжок, другая книга, чтение так и не начали) — файл осиротеет и будет
     *  удалён, как любая незапрошенная заготовка. */
    fun prewarm(text: String) {
        if (directMode || text.isBlank()) return
        val t = tts
        if (t == null || !ready) return
        if (currentText != null || awaitingPlayText != null || soundPlaying()) return
        if (prefetchInFlight.contains(text)) return
        // Роль этой фразы знаем так же, как её узнает synthToFile: реплика —
        // значит своя скорость, и «уже готово» надо сверять с ней же.
        val role = if (replyOn && !replyBroken && Roles.looksReplica(text)) {
            Pending.Role.REPLY
        } else {
            Pending.Role.MAIN
        }
        if (readyQueue.any { it.text == text && it.rate == rateFor(role) }) return
        if (keptPhrase?.let { it.text == text && it.rate == rateFor(role) } == true) return
        clearPrefetch()
        prefetchInFlight.add(text)
        prewarmOnly = true
        Diag.log(appContext, "sound", "готовлю первую фразу заранее (${text.length} знаков)")
        synthToFile(text)
    }

    /** Пауза с сохранением звука звучащей фразы: продолжение зазвучит сразу.
     *
     *  В паузе файл звучащей фразы никуда не девается — его удаляют только конец
     *  фразы или ошибка. А продолжение начинается с ТОЙ ЖЕ фразы (позицию
     *  читалка держит по предложениям и на паузе сохраняет её начало), поэтому
     *  его можно сыграть из того же файла, не заказывая синтез заново: по
     *  журналу это те же 0,5 с на фразу в десять секунд речи.
     *
     *  Скорость держим рядом с файлом: сменили её на паузе — файл прежнего
     *  темпа не играем (см. [takeKeptPhrase]).
     *
     *  Порядок важен: сначала [stop] (он чистит очередь, надзоры и заявки),
     *  потом ставим сохранённую фразу — иначе stop() снёс бы её как старую. */
    fun pauseKeepingPhrase() {
        val text = playingText
        val file = playingFile
        val rate = playingRate
        // У ExoPlayer позиция точная — запоминаем её, чтобы продолжение пошло с
        // середины фразы, а не с её начала.
        val pos = runCatching { filePlayer.positionMs }.getOrDefault(0L)
        stop()
        if (text != null && file != null && file.exists() && rate == rateFor(roleOfFile(file))) {
            keptPhrase = Prepared(text, file, rate, roleOfFile(file))
            keptPositionMs = pos
            Diag.log(
                appContext, "sound",
                "пауза: звук фразы сохранён (${file.name}, ${file.length()} байт) — продолжение зазвучит сразу"
            )
        } else {
            file?.delete() // продолжать не с чего — файл не копим
        }
    }

    /** Взять фразу, сохранённую паузой. Пригодилась — отдаём файл, играть его
     *  будет наш плеер. Не та фраза, сменившаяся скорость или пропавший файл —
     *  выбрасываем и читаем как обычно. */
    private fun takeKeptPhrase(text: String): Prepared? {
        val kept = keptPhrase ?: return null
        keptPhrase = null
        if (kept.text == text && kept.rate == rateFor(kept.role) && kept.file.exists()) {
            Diag.log(appContext, "sound", "продолжаю с сохранённого звука (${kept.file.name})")
            return kept
        }
        if (kept.text == text) {
            Diag.log(
                appContext, "sound",
                "сохранённый звук сделан на скорости ${RateSteps.label(kept.rate)}, " +
                    "сейчас ${RateSteps.label(speed)} — синтезирую заново"
            )
        }
        kept.file.delete()
        return null
    }

    /** Выбросить заготовки, сделанные прежней скоростью ([speed]). Текущий звук
     *  не трогаем: он уже звучит. Фразу в работе ([awaitingPlayText]) тоже не
     *  снимаем — её судьбу решит [synthFinished] по скорости самого файла. */
    private fun dropStaleRate() {
        prefetchInFlight.clear()
        prewarmOnly = false
        clearPrefetch()
        // 29.09.2026 (журнал 18:02, «покрутил всё»): в новом пути заготовки уезжают
        // в СПИСОК ПЛЕЕРА, и чистка очереди их не задевала. После смены скорости
        // там оставались файлы прежней скорости — они и звучали, а свежий файл на
        // тот же текст отбрасывался как «такая фраза уже есть в списке» (в журнале
        // это рядом: «синтез готов ... скорость 2.4» и «лишнюю не беру»). Хвост
        // списка убираем; звучащую фразу не трогаем — она дотягивается отношением
        // в [exoSyncSpeed].
        exoDropTail()
        keptPhrase?.let { runCatching { it.file.delete() } }
        keptPhrase = null
    }

    fun shutdown() {
        onDone = null
        onNeedNext = null
        stop()
        Diag.log(appContext, "tts", "закрываю плеер: ${replyCountersLine()}")
        dropReplyEngine()
        // 30.09.2026: усилитель прямого звука — отпускаем вместе с плеером.
        runCatching { boostEffect?.release() }
        boostEffect = null
        runCatching { tts?.shutdown() }
        tts = null
        ready = false
        // Чистим ТОЛЬКО свой каталог: общий вычищал бы заготовки соседнего
        // экземпляра (например, читалки, если закрывается пробный плеер настроек).
        runCatching { synthDir.deleteRecursively() }
    }

