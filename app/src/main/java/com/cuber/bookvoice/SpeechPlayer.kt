/**
 * Плеер озвучки, в котором звук играет САМО приложение, а не движок синтеза.
 *
 * Зачем. Пока голос произносил движок TextToSpeech напрямую, аудио числилось
 * за процессом движка — Android не считал BookVoice «плеером» и не отдавал
 * ему медиа-кнопки (гарнитура, «волшебное касание»): они уходили последнему
 * настоящему плееру (YouTube/Nekogram). Лог диагностики это подтвердил:
 * кнопка не доходила до приложения ни разу.
 *
 * Как теперь. Движок TTS только СИНТЕЗИРУЕТ предложение в wav-файл, а файл
 * проигрывает наш плеер (Media3 ExoPlayer, см. [FilePlayback]). Раз звук
 * физически играет из нашего процесса, система видит BookVoice как настоящий
 * плеер и отдаёт кнопки нам.
 *
 * Чтобы между предложениями не было пауз на синтез, фразы готовятся заранее:
 * пока играет текущая, читалка подсказывает через [onNeedNext] текст следующей,
 * и мы синтезируем её в файл. С msg4472 впрок держится не одна фраза, а
 * очередь из [prefetchDepth]: у тестеров на Poco и realme движок синтеза
 * замирал на 12–15 с (экран заблокирован), и с одной заготовкой это слышалось
 * как пауза, а с тремя — проходит незаметно.
 */
class SpeechPlayer(context: Context) {

    private val appContext = context.applicationContext
    private val main = Handler(Looper.getMainLooper())

    private var tts: TextToSpeech? = null
    private var ready = false
    private var engineReadyCallback: ((Boolean) -> Unit)? = null

    /** Пакет текущего движка синтеза (null — системный по умолчанию). */
    var enginePackage: String? = null
        private set

    var speed: Float = 1f
        set(value) {
            if (field == value) return
            field = value
            tts?.setSpeechRate(value)
            // 24.09.2026: заготовки сделаны прежней скоростью, и играть их
            // прежним темпом нельзя (см. [Prepared]). Выбрасываем сразу, а не
            // по одной на подходе: иначе три устаревшие фразы подряд собирались
            // бы заново без упреждения и чтение спотыкалось бы на каждой.
            dropStaleRate()
            // 29.09.2026: и сам звучащий файл подтягиваем на ходу — иначе новая
            // скорость слышна только с начала следующей фразы. У ExoPlayer темп
            // меняется его собственными параметрами, с сохранением высоты голоса.
            //
            // Файл звучит уже на скорости [exoPlayingRate] (его так записал
            // движок), поэтому плееру задаём отношение к новому ползунку: иначе
            // скорость применилась бы дважды — и движком, и плеером. Реплике
            // книжный ползунок не указ: у неё своя скорость.
            if (playingFile?.let { roleOfFile(it) } != Pending.Role.REPLY) {
                runCatching {
                    filePlayer.setSpeed((value / exoPlayingRate).coerceIn(0.25f, 4f))
                }
            }
        }

    /** Высота голоса (тон). Норма = 1.0. Движку задаётся для СЛЕДУЮЩЕГО синтеза,
     *  а уже звучащую фразу доводит плеер ([exoSyncSpeed]) — иначе новая высота
     *  слышна только с начала следующей фразы.
     *
     *  29.09.2026 (Серж: «кручу тон — срабатывает не мгновенно, а с задержкой
     *  большущей»): пока ползунок не выбрасывал заготовки, прежним тоном доигрывало
     *  ВСЁ, что стоит впереди (три-четыре фразы, до полусотни секунд звука), и ещё
     *  звучащая фраза. Теперь заготовки выбрасываются, а звучащая дотягивается. */
    var pitch: Float = 1f
        set(value) {
            val v = value.coerceIn(0.25f, 4f)
            if (field == v) return
            field = v
            tts?.setPitch(v)
            // Заготовки сделаны прежним тоном — играть их нельзя (та же причина,
            // что у смены скорости, поэтому и чистка та же).
            dropStaleRate()
            // Реплике книжный ползунок не указ: у неё своя высота.
            if (playingFile?.let { roleOfFile(it) } != Pending.Role.REPLY) {
                runCatching {
                    filePlayer.setPitch((v / exoPlayingPitch).coerceIn(0.25f, 4f))
                }
            }
        }

    /** Короткие паузы между предложениями (msg4402, просьба тестера
     *  @Spartach72). Мы озвучиваем каждое предложение отдельным файлом, и по
     *  краям движок оставляет тишину — в чтении по предложениям она слышна как
     *  пауза; здесь обрезаем эту тишину, оставляя короткие хвосты.
     *  msg4416: вторая половина той же правки живёт в ReaderEngine — соседние
     *  короткие предложения уходят в движок одной фразой. Обрезка работает не
     *  на всех движках (у DariyaNeural тишины по краям нет вовсе), но файл не
     *  портит, поэтому не выключается — галочку убрали (msg5254).
     *  msg5254: галочка «Короткие паузы между предложениями» убрана из настроек
     *  Сергеем — склейка и обрезка работают всегда, как было по умолчанию. */
    /** #57: альтернативный способ озвучки — фразу целиком отдаём движку
     *  ([fallbackDirect] как основной путь, проба для сравнения на слух,
     *  msg5401/5409). Обычно у нас наоборот: движок только готовит файл, а
     *  играет наш плеер.
     *
     *  Что при этом выключается: наши заготовки ([requestPrefetch]) — их
     *  работу движок делает сам. Сторож молчания продолжает работать, но своей
     *  веткой ([armDirectWatch]):
     *  он надзирает за прямой речью, а не за синтезом в файл, поэтому лестница
     *  мер «переспрос → перезапуск движка» здесь не взводится.
     *
     *  По умолчанию ВЫКЛ — настройка тестовая, обычное чтение не меняется. */
    var altDirect: Boolean = false
        set(value) {
            val was = field
            field = value
            // 30.09.2026: включился прямой режим — тихий поток встаёт вместе с ним.
            // В этом режиме звук играет движок, и без тихого потока система не
            // видит нас играющими: кнопки на наушниках уходят чужому плееру.
            // Раньше это делала галочка альтернативного способа в настройках, но
            // способ включается и не только ею (голосом, из читалки) — поэтому
            // следим здесь, в единственном месте, где режим и меняется.
            if (value && !was) {
                KeepAwake.enableSilenceAuto(appContext, "выбран альтернативный способ озвучки")
            }
        }

    /** Сетевой движок оказался не в состоянии отдавать файлы — читаем его
     *  голосом напрямую, как в альтернативном способе (29.09.2026).
     *
     *  Почему так. Просьба Сержа: «что если сделать так, чтобы сетевому
     *  синтезатору посылалась по одной фразе, как в альтернативной озвучке».
     *  Журнал 02:16 подтвердил: у сетевого голоса mstrans файл не приходит ни за
     *  5 секунд, ни после переспроса — каждая фраза кончалась прямой речью, то
     *  есть мы каждый раз делали лишний круг: заказ файла, ожидание, переспрос,
     *  и только потом то, что работает сразу. Смысла в этом круге нет.
     *
     *  Решение по ОПЫТУ, а не по названию движка: пока файлы приходят, работаем
     *  файлами (у них бесшовный стык и свой плеер), а если движок дважды подряд
     *  не отдал файл — переходим на прямую речь и запоминаем это для пары
     *  «движок + голос». Пометка переживает перезапуск приложения. */
    private var netDirect = false

    /** Читать движку напрямую: либо так выбрано в настройках, либо сетевой
     *  движок не отдаёт файлы (см. [netDirect]). */
    private val directMode: Boolean get() = altDirect || netDirect

    /** Текст фразы, которая звучит прямо сейчас. */
    private var playingText: String? = null

    /** Файл звучащей фразы и скорость, которой он сделан. Нужны паузе: файл при
     *  паузе никуда не удаляется, и продолжение можно начать с него же, не
     *  заставляя движок синтезировать ту же фразу второй раз (см.
     *  [pauseKeepingPhrase]). */
    private var playingFile: File? = null
    private var playingRate: Float = 1f

    /** Сколько раз за сессию журналируем пустой звук от движка (не спамить). */
    private var emptySoundLogged = 0

    /** Сколько тишины оставлять на стыке фраз, мс (msg5604).
     *
     *  Обрезка ([trimSilence]) снимает тишину, которую движок дописал по краям
     *  файла: у сетевых голосов Google её 518–680 мс на фразу, и без обрезки
     *  чтение шло «с паузами». Раньше остаток был прибит гвоздями (50 мс в
     *  голове + 83 мс в хвосте) — теперь его задаёт строка «Пауза между
     *  фразами» в настройках: значение делится между хвостом текущей фразы и
     *  головой следующей. 0 — срезать всю тишину, что дописал движок.
     *
     *  Чего настройка НЕ может: если движок паузу не молчанием, а интонацией
     *  (тянет последний слог) — тишины по краям нет вовсе, обрезка отступает
     *  (trimBail 9), и значение ничего не меняет. */
    var pauseKeepMs: Int = 130

    /** Громкость собственного звука (0..2; 1 = полная, как у системы).
     *  Умножается на системную громкость медиа. Применяется сразу к играющему
     *  предложению и к каждому следующему при старте.
     *
     *  26.09.2026: ползунок пускает до 200%, но плеер громче единицы не умеет —
     *  поэтому всё, что выше 100%, домножается в самом звуке при синтезе
     *  (см. trimSilence). Так тихий движок можно поднять, а не только убавить. */
    var volume: Float = 1f
        set(value) {
            val v = value.coerceIn(0f, 2f)
            val wasLoud = field > 1f
            field = v
            // Звучит ExoPlayer — громкость у него своя.
            runCatching { filePlayer.setVolume(v) }
            // 30.09.2026: выше 100% в ПРЯМОМ режиме движок не умеет — добавку
            // делает наш усилитель (см. [applyDirectBoost]).
            applyDirectBoost()
            if (wasLoud != (v > 1f)) {
                // Подстройка перешла через 100%: уже готовые фразы сделаны по
                // прежнему правилу — не играем их, иначе смена слышна не сразу.
                dropStaleReply()
            }
        }

    // ---------------- Усилитель прямого звука (30.09.2026) ----------------
    //
    // Приём взят у @Voice Aloud Reader: приложение заводит себе звуковой сеанс
    // (AudioManager.generateAudioSessionId), отдаёт его движку вместе с фразой
    // (KEY_PARAM_SESSION_ID) и вешает на этот сеанс LoudnessEnhancer.
    //
    //  Зачем. Ползунок громкости пускает до 200%. В файловом способе всё, что выше
    //  100%, домножается в самом звуке при синтезе (см. trimSilence) — работает,
    //  но требует пересборки готовых фраз. В прямом способе звук играет движок, и
    //  такого рычага у нас не было вовсе: параметр громкости движку больше единицы
    //  не передать, и тихий сетевой голос поднять было нечем. Усилитель живёт
    //  отдельно от звука: он прибавляет громкость уже играющему, и пересборка не
    //  нужна.
    //
    //  Что важно знать: усилитель умеет только ПРИБАВЛЯТЬ (убавляет по-прежнему
    //  параметр громкости), номер сеанса движок может и проигнорировать — тогда в
    //  прямом режиме ничего не меняется, вреда нет; на части прошивок эффект
    //  недоступен — тогда в журнал уходит строка, и мы больше не пробуем.

    /** Номер звукового сеанса, который отдаём движку. 0 — система не дала. */
    private var boostSession = 0
    private var boostEffect: LoudnessEnhancer? = null

    /** Усилитель не удался — второй раз не пробуем (в журнале уже сказано). */
    private var boostBroken = false

    /** Какая добавка уже объявлена в журнале: пишем только на изменение. */
    private var boostLoggedMb = Int.MIN_VALUE

    /** Сколько добавки просит ползунок, мБ. 0 — не выше 100%, добавка не нужна.
     *  Берём большее из двух громкостей (книги и реплик): сеанс у нас один. */
    private fun boostWantedMb(): Int = maxOf(
        if (volume > 1f) Math.round((volume - 1f) * 2400f) else 0,
        if (replyVolume > 1f) Math.round((replyVolume - 1f) * 2400f) else 0,
    )

    private fun boostSessionId(): Int {
        if (boostSession != 0) return boostSession
        boostSession = runCatching {
            (appContext.getSystemService(Context.AUDIO_SERVICE) as AudioManager)
                .generateAudioSessionId()
        }.getOrDefault(0)
        return boostSession
    }

    /** Привести усилитель в соответствие с ползунком. Зовётся на смену громкости
     *  и перед прямой речью — вызов безвреден и дёшев. */
    private fun applyDirectBoost() {
        val want = boostWantedMb()
        if (want <= 0) {
            if (boostLoggedMb != Int.MIN_VALUE) {
                runCatching { boostEffect?.enabled = false }
                Diag.log(appContext, "sound", "усилитель прямого звука выключен (громкость не выше 100%)")
                boostLoggedMb = Int.MIN_VALUE
            }
            return
        }
        if (boostBroken) return
        val session = boostSessionId()
        if (session <= 0) {
            boostBroken = true
            Diag.log(appContext, "sound", "усилитель прямого звука не вышел: система не дала звуковой сеанс")
            return
        }
        var e = boostEffect
        if (e == null) {
            val r = runCatching { LoudnessEnhancer(session) }
            e = r.getOrNull()
            if (e == null) {
                boostBroken = true
                Diag.log(appContext, "sound", "усилитель прямого звука недоступен: ${r.exceptionOrNull()}")
                return
            }
            boostEffect = e
            Diag.log(
                appContext, "sound",
                "усилитель прямого звука готов: сеанс $session, его же отдаю движку в параметрах speak"
            )
        }
        runCatching {
            e.setTargetGain(want)
            e.enabled = true
        }
        if (boostLoggedMb != want) {
            Diag.log(
                appContext, "sound",
                "усилитель прямого звука: добавка $want мБ (громкость ${Math.round(volume * 100)}%)"
            )
            boostLoggedMb = want
        }
    }

    private var selectedVoiceName: String? = null

    /** Вызывается на главном потоке, когда предложение дочитано до конца. */
    var onDone: (() -> Unit)? = null

    /** Возвращает текст фразы, которая прозвучит через [offset] фраз вперёд
     *  (1 — следующая), или null, если книга кончилась. Зовётся на главном
     *  потоке, без побочных эффектов.
     *
     *  msg4472: параметр появился вместе с очередью заготовок. Раньше мы
     *  синтезировали ровно одну фразу вперёд, и каждая заминка движка (в логе
     *  тестера — 12–15 с раз в минуту-полторы, экран заблокирован) слышалась
     *  как пауза: играть было нечего. Теперь держим [PREFETCH_DEPTH] фраз
     *  готовыми, и заминка проходит незаметно — звук идёт из заготовок. */
    var onNeedNext: ((Int) -> String?)? = null

    val isReady: Boolean get() = ready

    val voices: List<Voice>
        get() = tts?.voices?.toList() ?: emptyList()

    /** Пакет системного движка по умолчанию (может быть null до инициализации). */
    val defaultEngine: String?
        get() = tts?.defaultEngine

    /** Все установленные движки: пары (пакет, название). */
    val engines: List<Pair<String, String>>
        get() {
            val merged = LinkedHashMap<String, String>()
            for ((pkg, label) in queryEngines(appContext)) merged.putIfAbsent(pkg, label)
            tts?.engines?.forEach { e ->
                val name = e.name ?: return@forEach
                val label = e.label?.takeIf { it.isNotBlank() } ?: name
                merged.putIfAbsent(name, label)
            }
            return merged.toList().sortedBy { it.second.lowercase() }
        }

    // ---------- Пайплайн «синтез в файл → играет плеер» ----------

    /** Каталог временных файлов синтеза. У КАЖДОГО экземпляра он свой
     *  (30.09.2026). Прежде каталог был один на всех, и временный плеер,
     *  который поднимается в панели «Голос» для пробы голоса, при закрытии
     *  вычищал его ЦЕЛИКОМ — вместе с заготовками читалки. В журнале Сержа
     *  (00:47:23) это ровно и видно: он на ходу менял голос реплик, прогремело
     *  «закрываю плеер», файл, уже отданный плееру чтения, исчез с диска —
     *  и на нём вышло «Source error» (см. [exoListener.onError]). */
    private val synthDir = File(
        File(appContext.cacheDir, "tts_speech"),
        "p${instanceSeq.getAndIncrement()}",
    ).apply {
        if (!exists()) mkdirs()
    }

    // ---------------- Файлы играет ExoPlayer (28.09.2026) ----------------

    /** Плеер Media3 (см. [FilePlayback]). Поднимается лениво. */
    private val filePlayer: FilePlayback by lazy { FilePlayback(appContext) }

    /** Сколько заготовок отдано ExoPlayer ВПЕРЁД от звучащей фразы, и счётчик
     *  заявок для него: по ним понимаем, есть ли что играть дальше. */
    private var exoAhead = 0
    private var exoSeq = 0L

    /** ЗЕРКАЛО того, что уже отдано ExoPlayer и ещё не доиграло, в порядке
     *  звучания (первая — та, что звучит сейчас). Нужно затем, чтобы при вопросе
     *  чтения «играй вот эту фразу» понимать: она уже стоит впереди (тогда просто
     *  ждём) или её в списке нет (тогда выбрасываем хвост и дописываем её).
     *  Без него приходилось перезапускать список, и всё, что впереди, гибло —
     *  это и была потеря текста в сборке 187. */
    private val exoPending = ArrayDeque<Prepared>()

    /** Темп ФАЙЛА, который звучит сейчас. Движок пишет файл уже на нужной
     *  скорости ([Prepared.rate]), поэтому плееру остаётся только довести темп до
     *  нынешнего ползунка: играть такой файл на самой скорости — значит применить
     *  её дважды. Жалоба Сержа «словил очередную глюк после кручения скорости»
     *  (29.09.2026) — про это: в списке рядом лежали файлы, сделанные на 0.9, 1.2
     *  и 1.8, а плеер тянул их все на 1.2. */
    private var exoPlayingRate = 1f

    /** Тон ФАЙЛА, который звучит сейчас: движок записал его на этой высоте голоса,
     *  и плееру задаётся отношение «нужный тон / тон файла» ([exoSyncSpeed]).
