package com.cuber.bookvoice

/**
 * Прямая речь и герои: разбор по правилам русской типографики (26.09.2026).
 *
 *  Зачем отдельный объект. Реплику надо узнавать в двух местах: при чтении
 *  (чтобы отдать фразу второму голосу) и при подсчёте (сколько в главе реплик и
 *  кто в них назван). Оба места обязаны понимать текст одинаково, иначе числа в
 *  журнале перестанут сходиться с тем, что слышно.
 *
 *  Главное правило: реплика — это предложение, которое начинается с длинного
 *  тире. В русской книге так помечают прямую речь, а наш разбор уже режет текст
 *  по предложениям и хранит признак «предложение начинает абзац». Обычный дефис
 *  в начале строки репликой НЕ считаем: это чаще пункт списка или линейка.
 *
 *  Чего здесь сознательно нет: приписывания реплик героям по смыслу. «— ответил
 *  он» героя не даёт, и придумывать его нельзя — ошибка была бы слышна, а
 *  проверить её незрячему нечем. Берём только то, что названо прямо: «— сказал
 *  Иван».
 */
object Roles {

    /** Тире, которыми в книгах помечают реплику. Дефис-минус сюда не входит. */
    private val DASHES = charArrayOf('—', '–', '−')

    /** Реплика ли эта фраза. */
    fun looksReplica(text: String): Boolean {
        val s = text.trimStart()
        if (s.isEmpty()) return false
        return DASHES.contains(s[0])
    }

    /** Разделитель ли эта строка: «* * *», «— — —», «...», «• • •». Такие строки
     *  ставят между рассказами, анекдотами и сценами — и часто это единственная
     *  граница в книге (26.09.2026: в сборнике анекдотов глав нет вовсе, весь
     *  файл — одна секция, а между анекдотами стоит подзаголовок «* * *»).
     *
     *  Правило узкое и проверяемое: в строке нет ни букв, ни цифр, не больше
     *  двенадцати знаков, и знаков-разделителей минимум два. Одиночное тире или
     *  точка разделителем не считаются — это знак препинания, а не граница. */
    private val SEPARATOR_CHARS = setOf(
        '*', '-', '–', '—', '−', '.', '…', '•', '·', '~', '=', '+', '×', '❋', '✳',
    )

    fun looksSeparator(text: String): Boolean {
        val s = text.trim()
        if (s.isEmpty() || s.length > 12) return false
        var marks = 0
        for (c in s) {
            if (c.isLetterOrDigit()) return false
            if (c.isWhitespace()) continue
            if (c !in SEPARATOR_CHARS) return false
            marks++
        }
        return marks >= 2
    }

    /** Слова автора: по ним видно, что рядом назван говорящий. Список нарочно
     *  короткий и частотный — он нужен для счёта, а не для понимания текста. */
    private val SPEECH_VERBS = setOf(
        "сказал", "сказала", "сказали", "говорит", "говорю", "ответил", "ответила",
        "ответили", "спросил", "спросила", "спросили", "произнёс", "произнес",
        "произнесла", "проговорил", "проговорила", "крикнул", "крикнула", "шепнул",
        "шепнула", "прошептал", "прошептала", "заметил", "заметила", "добавил",
        "добавила", "повторил", "повторила", "возразил", "возразила", "согласился",
        "согласилась", "усмехнулся", "усмехнулась", "улыбнулся", "улыбнулась",
        "продолжил", "продолжила", "перебил", "перебила", "воскликнул",
        "воскликнула", "пробормотал", "пробормотала", "вздохнул", "вздохнула",
        "засмеялся", "засмеялась", "буркнул", "буркнула", "позвал", "позвала",
        "отозвался", "отозвалась", "рявкнул", "ответствует", "спрашивает",
        "отвечает", "говорит", "промолвил", "промолвила", "объявил", "объявила",
        "предупредил", "предупредила", "поинтересовался", "поинтересовалась",
    )

    /** Слова, которые именем не являются: местоимения и общие названия людей.
     *  Без этого «— сказал он» давало бы героя по имени «он». */
    private val NOT_NAMES = setOf(
        "он", "она", "оно", "они", "его", "её", "ее", "ему", "ей", "их", "им",
        "ими", "я", "ты", "мы", "вы", "все", "всё", "всех", "это", "этот", "эта",
        "эти", "тот", "та", "те", "кто", "что", "никто", "некто", "кто-то",
        "что-то", "парень", "девушка", "мужчина", "женщина", "старик", "старуха",
        "голос", "господин", "госпожа", "товарищ", "доктор", "мама", "папа",
        "отец", "мать", "сын", "дочь", "брат", "сестра", "друг", "подруга",
        "человек", "люди", "хозяин", "хозяйка", "мальчик", "девочка",
    )

    /** Имя говорящего из авторских слов: «— сказал Иван», «Иван сказал».
     *  null — герой не назван прямо («— сказал он»). Врать тут нельзя. */
    fun namedSpeaker(text: String): String? {
        val words = text.split(' ', '\n', '\t', ',', ';', ':', '—', '–', '−', '!', '?', '…', '«', '»', '(', ')')
            .filter { it.isNotBlank() }
        for ((i, raw) in words.withIndex()) {
            val w = raw.trim { !it.isLetter() }.lowercase()
            if (w.isEmpty() || w !in SPEECH_VERBS) continue
            nameAt(words, i + 1)?.let { return it }
            nameAt(words, i - 1)?.let { return it }
        }
        return null
    }

    /** Слово по индексу, если оно похоже на имя: с большой буквы, не местоимение,
     *  только буквы (допускаем дефис внутри: «Пьер-Луи»). */
    private fun nameAt(words: List<String>, idx: Int): String? {
        val raw = words.getOrNull(idx)?.trim() ?: return null
        if (raw.isEmpty() || !raw[0].isUpperCase()) return null
        val core = raw.trim { !it.isLetter() && it != '-' }
        if (core.length < 3) return null
        if (core.any { !it.isLetter() && it != '-' }) return null
        if (core.lowercase() in NOT_NAMES) return null
        return core
    }

    /** Что нашлось в главе: сколько предложений, сколько из них реплики и кто
     *  из говорящих назван прямо. Числа идут в журнал — по ним решается,
     *  стоит ли раздавать голоса героям. */
    data class Stats(val sentences: Int, val replies: Int, val named: Map<String, Int>)

    fun stats(sentences: List<Sentence>): Stats {
        var replies = 0
        val named = HashMap<String, Int>()
        for (s in sentences) {
            if (!looksReplica(s.text)) continue
            replies++
            namedSpeaker(s.text)?.let { named[it] = (named[it] ?: 0) + 1 }
        }
        return Stats(sentences.size, replies, named)
    }

    /** Короткая строка для журнала: «реплик 12 из 210 (6%), названы: Иван 5, Марья 3». */
    fun statsLine(s: Stats): String {
        val pct = if (s.sentences == 0) 0 else s.replies * 100 / s.sentences
        val top = s.named.entries.sortedByDescending { it.value }.take(3)
            .joinToString(", ") { "${it.key} ${it.value}" }
        val tail = if (top.isEmpty()) "названных героев нет" else "названы: $top"
        return "реплик ${s.replies} из ${s.sentences} ($pct%), $tail"
    }
}
