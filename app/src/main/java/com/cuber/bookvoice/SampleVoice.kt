package com.cuber.bookvoice

import android.content.Context

/**
 * Плеер образца фразы — ОДИН на приложение (29.10.2026).
 *
 * Зачем вынесен. Жалоба Сержа: «когда выходишь из диалога настроек голоса, фраза
 * обрывалась бы при входе в читаемую книжку из этого окошка» — то есть образец
 * голоса договаривал уже в открытой книге, поверх чтения. Образец до этого жил
 * внутри [VoicePicker], и погасить его из другого места было нечем: экземпляр
 * набора настроек к читалке отношения не имеет.
 *
 * Правило теперь простое: ЛЮБОЕ начало чтения книги гасит образец
 * ([ReaderEngine.startSpeakingCurrent]), и закрытие списка голосов гасит его тоже
 * ([VoicePicker]). Плеер при этом не уничтожается — следующий выбор голоса
 * зазвучит сразу, без подъёма движка.
 */
object SampleVoice {

    private var player: SpeechPlayer? = null

    /** Плеер образца; поднимается при первом обращении. */
    fun take(ctx: Context): SpeechPlayer =
        player ?: SpeechPlayer(ctx.applicationContext).also { player = it }

    /** Оборвать образец (чтение книги началось). Плеер остаётся живым. */
    fun stop() {
        player?.stop()
    }

    /** Погасить совсем — уход из Настроек: движок за собой держать незачем. */
    fun shutdown() {
        player?.shutdown()
        player = null
    }
}
