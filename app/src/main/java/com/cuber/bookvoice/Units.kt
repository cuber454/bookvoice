package com.cuber.bookvoice

/** ЕДИНИЦА РЕЧИ: фраза книги вместе с номером своего куска (08.10.2026).
 *
 *  Зачем это отдельным файлом. До 8 октября опознанием фразы служили её ТЕКСТ и
 *  позиция, а куски одной фразы (слова автора и реплика, «голова и хвост» после
 *  укороченной первой фразы) шли с ОДНОЙ позицией — различить их было нечем.
 *  Отсюда две беды, которые Серж слышал как «фраза прозвучала дважды» (журнал
 *  21:43 и 12:45): хвост фразы вставал в список плеера ПОСЛЕ следующего
 *  предложения, а чтение, услышав конец чужого файла, двигало указатель и
 *  просило уже прозвучавшее.
 *
 *  Теперь у каждой единицы есть КЛЮЧ — позиция и номер куска одним числом, — и он
 *  один служит опознанием везде: в очереди заготовок, в списке плеера, в кэше
 *  сыгранных фраз и в отчёте «доиграла». Текст опознанием быть не может: в книге
 *  полно одинаковых фраз. Формула ключа живёт ТОЛЬКО здесь — второй такой же быть
 *  не должно.
 *
 *  Проверить порядок единиц по книге можно было строкой «Проверить порядок» в
 *  опытных настройках; 09.10.2026 её убрали — прибор понадобился, пока чинили
 *  порядок, а сейчас порядок проверяется живым чтением. */
internal object Units {

    /** Сколько кусков может быть у одной фразы. Больше сотни не бывает ни у
     *  одной фразы, а место в Long это оставляет с запасом. */
    const val PARTS_MAX = 100

    /** Ключ единицы речи: позиция фразы в книге и номер её куска одним числом.
     *  Позиция меньше нуля — места нет (служебные фразы): ключ тоже -1. */
    fun key(pos: Long, part: Int): Long =
        if (pos < 0) -1L else pos * PARTS_MAX + part.coerceIn(0, PARTS_MAX - 1)

    /** Единица речи словами — для журнала, настроек и ответа вслух. Номера те
     *  же, что печатает чтение («глава 24» — это и есть 24-я глава книги, а не
     *  24-й индекс): прибавленная единица однажды уже сбила разбор журнала с
     *  толку, поэтому НЕ прибавлять. */
    fun label(pos: Long, part: Int): String =
        if (pos < 0) "без места в книге"
        else "глава ${pos / 1_000_000L}, предл. ${pos % 1_000_000L}, кусок $part"

    /** Единица речи по её ключу — словами (для журнала). */
    fun labelOfKey(key: Long): String =
        if (key < 0) "неизвестно"
        else label(key / PARTS_MAX, (key % PARTS_MAX).toInt())
}
