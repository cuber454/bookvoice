package com.cuber.bookvoice

/**
 * Значения ползунков скорости и тона (msg3929, msg3933).
 *
 * Скорость: 0.5–4.0 ровным шагом 0.1 — как и было прежде, только потолок выше
 * (msg3933: на 5.0 с укрупнённым шагом Сергей не согласился, хочет по одной
 * десятой на всём диапазоне).
 *
 * Тон оставлен прежним (0.5–2.0 шагом 0.1): выше двух он не значит ничего
 * хорошего, а привычку менять незачем.
 *
 * Значения — единственный источник и для ползунка в настройках
 * (SettingsActivity.addRateSlider), и для ползунков диалога голоса
 * (MainActivity.addRateSliderTo), и для кнопок «Медленнее/Быстрее»
 * (MainActivity.nudgeSpeed).
 */
object RateSteps {

    /** 0.5 … 10.0 ровным шагом 0.1 — 96 значений.
     *
     *  msg5979: потолок 4.0 поднят до 6.0 «и потом протестируем». 05.10.2026
     *  Серж попросил до 10.0: «бывает медленные синтезаторы», им и нужен запас
     *  сверху. Шаг оставлен прежним — по одной десятой на всём диапазоне (на 5.0
     *  с укрупнённым шагом он не согласился, msg3933).
     *
     *  Смысл именно в проверке: наш ползунок ничего не зажимает, значение уходит
     *  движку (`SpeechPlayer.speed` → `setSpeechRate`), а выше двух у каждого
     *  движка свой настоящий предел — заказ 10.0 он вправе проигнорировать.
     *  Где предел на самом деле, видно по размеру файлов в журнале (см.
     *  `synthFinished`). Ничего при этом не ломается: файл придёт на скорости
     *  движка, а плеер дотянет его отношением не больше четырёх (`exoSyncSpeed`),
     *  у сторожа свой потолок ([SpeechPlayer.charsPerSec] — 80 знаков в секунду),
     *  и он от высокой скорости только терпеливее. */
    val SPEED: List<Float> = tenths(0.5f, 10.0f)

    /** 0.5 … 2.0 шагом 0.1 — как было. */
    val PITCH: List<Float> = tenths(0.5f, 2.0f)

    /** На сколько десятых двигать скорость на один свайп скринридером — в
     *  зависимости от того, где ползунок стоит сейчас (06.10.2026).
     *
     *  Было так: Android сам берёт пятую часть диапазона (`round((max − min) / 20)`,
     *  у нас 95 шагов → 5 шагов), и свайп прыгал через 0.5. Серж: «перекручивает
     *  сразу по пять десятых, 1.5, 2, 2.5 — как бы хотя бы по 2/10». Но и ровные
     *  0.2 по всему диапазону — не середина: они пропускают нечётные десятые
     *  (1.3 и 1.5 не поставить), а выше 3.0 такой шаг уже мельче, чем ухо
     *  различает.
     *
     *  Поэтому шаг разный: до 2.0 — одна десятая (зона, где человек и подбирает
     *  себе темп: 0.1 там это 5–12% разницы, слышно отчётливо), от 2.0 до 4.0 —
     *  две, выше — пять. Смысл: шаг примерно одинаков на слух, а не на бумаге.
     *  Весь путь 0.5 → 10.0 — 37 свайпов вместо 15 при шаге 0.5 (и вместо 95,
     *  если делать всё по одной десятой). */
    fun speedSwipeStep(v: Float): Int = when {
        v < 2.0f -> 1
        v < 4.0f -> 2
        else -> 5
    }

    /** Десятые от [from] до [to] включительно. Число значений считается по
     *  границам, а не задано числом: потолок поменяется — список сам за ним
     *  потянется. */
    private fun tenths(from: Float, to: Float): List<Float> {
        val n = Math.round((to - from) * 10f)
        return (0..n).map { from + it * 0.1f }
    }

    /** Подпись значения: «1.0», «3.4». Через «%.2f» с отбрасыванием хвостового
     *  нуля, чтобы накопленная в float-сложении пыль (0.70000005) не всплыла
     *  в озвучке лишним знаком. */
    fun label(v: Float): String {
        val s = String.format(java.util.Locale.ROOT, "%.2f", v)
        return if (s.endsWith("0")) s.dropLast(1) else s
    }

    /** Ближайшее к [v] значение из [values]: им показываем сохранённую настройку,
     *  даже если она не совпадает с шагом (например, записана старой версией). */
    fun indexOf(values: List<Float>, v: Float): Int {
        var best = 0
        var bestDiff = Float.MAX_VALUE
        for (i in values.indices) {
            val d = kotlin.math.abs(values[i] - v)
            if (d < bestDiff) {
                bestDiff = d
                best = i
            }
        }
        return best
    }

    /** Соседнее значение по списку — шаг «медленнее/быстрее». На границе
     *  возвращает то же значение: вызывающий сам решает, что это «дальше некуда». */
    fun neighbour(values: List<Float>, v: Float, up: Boolean): Float {
        val i = indexOf(values, v)
        val ni = (i + if (up) 1 else -1).coerceIn(0, values.size - 1)
        return values[ni]
    }
}
