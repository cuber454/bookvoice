package com.cuber.bookvoice

import android.content.Context

/** Переход настроек чтения на новый смысл (24.10.2026).
 *
 *  Что случилось. Способы чтения поменялись местами: обычным стало чтение
 *  ГОЛОСОМ ДВИЖКА (как у @Voice Aloud Reader), а прежний файловый путь (движок
 *  пишет файл, играет наша читалка) стал обходным — его включает строка «Читать
 *  файлами (обходной способ)» ([MainActivity.KEY_READ_FILES], по умолчанию
 *  выключена).
 *
 *  Зачем отдельный объект. Прежний ключ (`alt_direct_voice`, [MainActivity.KEY_ALT_VOICE])
 *  означал ДРУГОЕ: включён — «читать голосом движка», выключен — «файлами». Если
 *  просто поменять умолчание у того же ключа, у всех, кто галочку СНИМАЛ (то есть
 *  осознанно выбирал файлы), она молча станет «читать голосом». Поэтому:
 *
 *  1) новый ключ заводим отдельно, смысл старого не переворачиваем;
 *  2) старый ключ НЕ удаляем — если человек откатится на прежнюю версию, у него
 *     всё останется как было;
 *  3) различаем «трогал» и «не трогал» по `contains`: галочка пишет значение
 *     только когда её касаются (`SettingsActivity.addCheck`), поэтому пустой
 *     ключ честно значит «человек выбора не делал».
 *
 *  Правила перехода:
 *  - новый ключ уже есть — ничего не трогаем (миграция уже была);
 *  - старого ключа нет — новое умолчание (голосом), писать нечего;
 *  - старый ВКЛЮЧЁН — голосом (это и был его выбор);
 *  - старый ВЫКЛЮЧЕН — файлами (человек сам снимал галочку, выбор уважаем).
 */
object PrefsMigration {

    /** Файл настроек чтения — как у [SpeechPlayer], [ExpertPrefs] и [ReadingMode]. */
    private const val PREFS = "reader"

    /** Состояние «читать файлами» с учётом миграции. Одно место чтения ключа:
     *  остальные зовут это, чтобы смысл не разъехался по файлам. */
    fun readFiles(c: Context): Boolean = runCatching {
        c.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
            .getBoolean(MainActivity.KEY_READ_FILES, false)
    }.getOrDefault(false)

    /** Отметка «тихий поток уже сбросили на выключенный»: чтобы сделать это один
     *  раз, а не при каждом запуске (человек вправе включить галочку обратно). */
    private const val KEY_SILENT_OFF_DONE = "silent_keepalive_auto_off_done"

    /** Переход на новый способ чтения один раз на старте процесса
     *  ([BookVoiceApp]). РЕШЕНИЕ СЕРЖА 24.10.2026: «после установки всё сбросить на
     *  умолчание движка; кто захочет вернуться к старому — включит „по файлам“ в
     *  настройках». Поэтому прежний выбор НЕ переносим: старая галочка в положении
     *  «выключено» и была умолчанием файлового пути — её никто не снимал ради
     *  файлов, её просто не трогали. Здесь только журнал: по нему видно, что у
     *  человека осталось с прежних версий. Старый ключ НЕ удаляем — чтобы откат на
     *  прежнюю версию не оставил человека без настроек.
     *
     *  Второе дело того же дня (24.10.2026, вечер): «Не давать Bluetooth засыпать»
     *  по умолчанию должна быть ВЫКЛЮЧЕНА (просьба Сержа: «пускай по умолчанию
     *  будет выключена»). У тех, кто читал прошлыми сборками, она стоит включённой
     *  не по своей воле: с 229 тихий поток поднимался сам, как только звук начинал
     *  произносить движок. Сам он больше не поднимается
     *  ([KeepAwake.noteDirectNeedsSilence]), а здесь мы один раз снимаем и остаток
     *  того самовключения. Дальше ключ наш: включит человек — так и останется. */
    fun migrate(c: Context) {
        val p = runCatching { c.getSharedPreferences(PREFS, Context.MODE_PRIVATE) }.getOrNull()
            ?: return
        val hadOld = p.contains(MainActivity.KEY_ALT_VOICE)
        val oldValue = if (hadOld) p.getBoolean(MainActivity.KEY_ALT_VOICE, false) else false
        val filesNow = p.getBoolean(MainActivity.KEY_READ_FILES, false)
        Diag.log(
            c, "settings",
            "способ чтения: обычный — голосом движка (новое умолчание); " +
                "файлами: ${if (filesNow) "ВКЛЮЧЕНО человеком" else "выключено"}; " +
                if (hadOld) {
                    "прежняя галочка была ${if (oldValue) "включена" else "выключена"} — " +
                        "её НЕ переносим (решение Сержа 24.10.2026)"
                } else {
                    "прежней галочки не было — сразу новое умолчание"
                },
        )
        // Тихий поток: один раз снимаем самовключение прежних сборок.
        if (!p.getBoolean(KEY_SILENT_OFF_DONE, false)) {
            val silentWas = p.getBoolean(MainActivity.KEY_SILENT_KEEPALIVE, false)
            p.edit()
                .putBoolean(MainActivity.KEY_SILENT_KEEPALIVE, false)
                .putBoolean(KEY_SILENT_OFF_DONE, true)
                .apply()
            Diag.log(
                c, "settings",
                "тихий поток («Не давать Bluetooth засыпать») — теперь по умолчанию " +
                    "выключен; было ${if (silentWas) "включено (ставили сами)" else "выключено"}. " +
                    "Включается только галочкой в «Чтении» → «Звук и стыки»",
            )
        }
    }
}
